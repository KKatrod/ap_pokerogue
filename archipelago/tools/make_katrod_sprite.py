"""
Builds src/archipelago/ap-katrod-sprite.ts: the sprite of Katrod (Katrod encounter), drawn from
archipelago/tools/katrod_sprite.png, trimmed and placed in a 80x80 source like the trainer sprites of the game (feet
at the bottom). Run: python archipelago/tools/make_katrod_sprite.py
"""

import base64
import io
import os

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SOURCE = os.path.join(ROOT, "archipelago", "tools", "katrod_sprite.png")
OUTPUT = os.path.join(ROOT, "src", "archipelago", "ap-katrod-sprite.ts")
FRAME = 80


def main():
    sprite = Image.open(SOURCE).convert("RGBA")
    sprite = sprite.crop(sprite.getbbox())
    # Trimmed frame, like the trainer atlases of the game: the shadow under the sprite takes the frame width
    x, y = (FRAME - sprite.width) // 2, FRAME - sprite.height
    buffer = io.BytesIO()
    sprite.save(buffer, "PNG", optimize=True)
    data = base64.b64encode(buffer.getvalue()).decode("ascii")
    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by archipelago/tools/make_katrod_sprite.py - do not edit by hand.\n")
        f.write("/** Katrod, the trainer of the Katrod encounter (one frame trimmed in a 80x80 source, like the trainers) */\n")
        f.write('export const AP_KATROD_SPRITE_KEY = "ap_katrod";\n')
        f.write(f"export const AP_KATROD_SPRITE_FRAME = {{ w: {sprite.width}, h: {sprite.height} }};\n")
        f.write(f"export const AP_KATROD_SPRITE_SOURCE = {{ x: {x}, y: {y}, w: {FRAME}, h: {FRAME} }};\n")
        f.write(f'export const AP_KATROD_SPRITE_DATA_URI = "data:image/png;base64,{data}";\n')
    print(f"Wrote {OUTPUT} ({sprite.width}x{sprite.height} sprite)")


if __name__ == "__main__":
    main()
