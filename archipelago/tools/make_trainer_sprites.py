"""
Builds the trainer sprites of the Archipelago encounters from their PNG files in archipelago/tools:
- katrod_sprite.png -> src/archipelago/ap-katrod-sprite.ts (Katrod encounter)
- oak_sprite.png -> src/archipelago/ap-oak-sprite.ts (Professor Oak encounter)
Each sprite is trimmed (and scaled down when taller than 76 px, the tallest that fits above its platform) and placed in
a source frame like the trainer sprites of the game (80x80 at least, feet at the bottom). Run: python archipelago/tools/make_trainer_sprites.py
"""

import base64
import io
import os

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
TOOLS = os.path.join(ROOT, "archipelago", "tools")
OUTPUT = os.path.join(ROOT, "src", "archipelago")
MIN_FRAME = 80
# Tallest sprite that fits above its platform in the field (like the Scientist): taller ones are scaled down
MAX_HEIGHT = 76

# (source PNG, output module, constant prefix, sprite key, description)
SPRITES = [
    ("katrod_sprite.png", "ap-katrod-sprite.ts", "AP_KATROD_SPRITE", "ap_katrod",
     "Katrod, the trainer of the Katrod encounter"),
    ("oak_sprite.png", "ap-oak-sprite.ts", "AP_OAK_SPRITE", "ap_oak",
     "Professor Oak, of the Professor Oak encounter"),
]


def build(source: str, output: str, prefix: str, key: str, description: str) -> None:
    sprite = Image.open(os.path.join(TOOLS, source)).convert("RGBA")
    sprite = sprite.crop(sprite.getbbox())
    if sprite.height > MAX_HEIGHT:
        width = round(sprite.width * MAX_HEIGHT / sprite.height)
        sprite = sprite.resize((width, MAX_HEIGHT), Image.NEAREST)
    # Trimmed frame, like the trainer atlases of the game: the shadow under the sprite takes the frame width
    frame = max(MIN_FRAME, sprite.width, sprite.height)
    x, y = (frame - sprite.width) // 2, frame - sprite.height
    buffer = io.BytesIO()
    sprite.save(buffer, "PNG", optimize=True)
    data = base64.b64encode(buffer.getvalue()).decode("ascii")
    path = os.path.join(OUTPUT, output)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by archipelago/tools/make_trainer_sprites.py - do not edit by hand.\n")
        f.write(f"/** {description} (one frame trimmed in a {frame}x{frame} source, like the trainers) */\n")
        f.write(f'export const {prefix}_KEY = "{key}";\n')
        f.write(f"export const {prefix}_FRAME = {{ w: {sprite.width}, h: {sprite.height} }};\n")
        f.write(f"export const {prefix}_SOURCE = {{ x: {x}, y: {y}, w: {frame}, h: {frame} }};\n")
        f.write(f'export const {prefix}_DATA_URI = "data:image/png;base64,{data}";\n')
    print(f"Wrote {path} ({sprite.width}x{sprite.height} sprite)")


if __name__ == "__main__":
    for entry in SPRITES:
        build(*entry)
