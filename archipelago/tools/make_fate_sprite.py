"""
Builds src/archipelago/ap-fate-sprite.ts: the Mega Alakazam sprite of the game with its 5 spoons recoloured with the
colours of the Archipelago logo (sprite of the "See the Fate" mystery encounter).

Usage: python archipelago/tools/make_fate_sprite.py
"""
import base64
import io
import os
from collections import deque

from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
SOURCE = os.path.join(ROOT, "assets", "images", "pokemon", "65-mega.png")
OUTPUT = os.path.join(ROOT, "src", "archipelago", "ap-fate-sprite.ts")

# Colours of the Archipelago logo, for the spoons from left to right (same layout as the logo: blue and yellow on
# the left, red on top, green and purple on the right)
SPOON_COLORS = [(118, 126, 189), (238, 227, 145), (201, 118, 130), (117, 194, 117), (202, 148, 194)]
# The spoons float above the head: only this band of the sprite is recoloured
SPOON_BAND_HEIGHT = 34
# Grey shades of the spoons (outline excluded), from dark to light
GREYS = {(134, 139, 145): 0.62, (180, 180, 180): 1.0, (222, 222, 222): 1.25, (251, 251, 251): 1.45}


def shade(color, factor):
    if factor <= 1:
        return tuple(round(c * factor) for c in color) + (255,)
    # Lighter: towards white
    t = factor - 1
    return tuple(round(c + (255 - c) * t) for c in color) + (255,)


def main():
    image = Image.open(SOURCE).convert("RGBA")
    pixels = image.load()
    width = image.width
    # Grey pixels of the spoon band, grouped by spoon (8-connected)
    grey = {(x, y) for y in range(SPOON_BAND_HEIGHT) for x in range(width) if pixels[x, y][:3] in GREYS
            and pixels[x, y][3] > 0}
    spoons = []
    seen = set()
    for start in sorted(grey):
        if start in seen:
            continue
        group, queue = [], deque([start])
        seen.add(start)
        while queue:
            x, y = queue.popleft()
            group.append((x, y))
            for dx in (-1, 0, 1):
                for dy in (-1, 0, 1):
                    n = (x + dx, y + dy)
                    if n in grey and n not in seen:
                        seen.add(n)
                        queue.append(n)
        spoons.append(group)
    spoons = [s for s in spoons if len(s) >= 6]
    if len(spoons) != len(SPOON_COLORS):
        raise SystemExit(f"Expected {len(SPOON_COLORS)} spoons, found {len(spoons)}")
    spoons.sort(key=lambda s: sum(x for x, _y in s) / len(s))
    for spoon, color in zip(spoons, SPOON_COLORS):
        for x, y in spoon:
            pixels[x, y] = shade(color, GREYS[pixels[x, y][:3]])

    buffer = io.BytesIO()
    image.save(buffer, "PNG", optimize=True)
    data = base64.b64encode(buffer.getvalue()).decode("ascii")
    frame_w, frame_h = 84, 89
    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by archipelago/tools/make_fate_sprite.py - do not edit by hand.\n")
        f.write("/** Mega Alakazam with its spoons in the colours of the Archipelago logo (\"See the Fate\" encounter) */\n")
        f.write('export const AP_FATE_SPRITE_KEY = "ap_fate_alakazam";\n')
        f.write(f"export const AP_FATE_SPRITE_SIZE = {{ w: {image.width}, h: {image.height} }};\n")
        f.write(f"export const AP_FATE_SPRITE_FRAME = {{ w: {frame_w}, h: {frame_h} }};\n")
        f.write(f'export const AP_FATE_SPRITE_DATA_URI = "data:image/png;base64,{data}";\n')
    image.crop((0, 0, frame_w, frame_h)).resize((frame_w * 6, frame_h * 6), Image.NEAREST).save(
        os.path.join(os.environ.get("TEMP", "."), "ap_fate_preview.png"))
    print(f"Wrote {OUTPUT} ({len(spoons)} spoons recoloured)")


if __name__ == "__main__":
    main()
