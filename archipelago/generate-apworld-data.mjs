// Generates archipelago/apworld/pokerogue/data.py from the game sources so that the apworld
// and the game client always share the same item / location ids.
//
// Usage: node archipelago/generate-apworld-data.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const apData = JSON.parse(readFileSync(join(root, "src/archipelago/ap-data.json"), "utf-8"));

// --- SpeciesId enum (sequential values with explicit overrides) ---
const speciesSrc = readFileSync(join(root, "src/enums/species-id.ts"), "utf-8");
const enumBody = speciesSrc.slice(speciesSrc.indexOf("{") + 1, speciesSrc.lastIndexOf("}"));
const speciesIds = {};
let next = 0;
for (const rawLine of enumBody.split(/\r?\n/)) {
  const line = rawLine
    .replace(/\/\*.*?\*\//g, "")
    .replace(/\/\/.*$/, "")
    .trim();
  const match = /^([A-Z0-9_]+)\s*(?:=\s*(\d+))?\s*,?$/.exec(line);
  if (!match) {
    continue;
  }
  const value = match[2] === undefined ? next : Number.parseInt(match[2]);
  speciesIds[match[1]] = value;
  next = value + 1;
}

// --- Starters: species data entries that define a `starterCost` (src/data/balance/species/generation-XX.ts) ---
const speciesDir = join(root, "src/data/balance/species");
const starters = [];
for (const file of readdirSync(speciesDir)
  .filter(f => /^generation-\d+\.ts$/.test(f))
  .sort()) {
  const src = readFileSync(join(speciesDir, file), "utf-8");
  // Each species is declared as `generationXSpeciesData[SpeciesId.NAME] = { ... }`
  const blocks = src.split(/SpeciesData\[SpeciesId\./).slice(1);
  for (const block of blocks) {
    const key = /^([A-Z0-9_]+)\]/.exec(block)?.[1];
    const cost = /\bstarterCost:\s*(\d+)/.exec(block)?.[1];
    // The first generation / types of the block are the species' own (its forms come after)
    const generation = /\bgeneration:\s*(\d+)/.exec(block)?.[1];
    const type1 = /\btype1:\s*PokemonType\.([A-Z]+)/.exec(block)?.[1];
    const type2 = /\btype2:\s*(?:PokemonType\.([A-Z]+)|null|undefined)/.exec(block)?.[1];
    if (key && cost) {
      if (!(generation && type1)) {
        throw new Error(`Could not parse the generation / types of ${key}`);
      }
      const types = [type1, ...(type2 && type2 !== type1 ? [type2] : [])];
      starters.push({ key, cost: Number.parseInt(cost), generation: Number.parseInt(generation), types });
    }
  }
}

const toTitle = key =>
  key
    .split("_")
    .map(w => w.charAt(0) + w.slice(1).toLowerCase())
    .join(" ");

const pokemon = starters
  .filter(s => speciesIds[s.key] !== undefined)
  .map(s => ({
    name: `Pokemon - ${toTitle(s.key)}`,
    id: apData.base_id + apData.pokemon_item_offset + speciesIds[s.key],
    cost: s.cost,
    generation: s.generation,
    types: s.types,
  }));

// --- Biomes: BiomeId enum and the links of each biome (src/data/balance/biomes/*.ts) ---
const biomeEnumSrc = readFileSync(join(root, "src/enums/biome-id.ts"), "utf-8");
const biomeIds = {};
for (const match of biomeEnumSrc.matchAll(/^\s*([A-Z_]+):\s*(\d+),/gm)) {
  biomeIds[match[1]] = Number.parseInt(match[2]);
}
const biomesDir = join(root, "src/data/balance/biomes");
const biomes = [];
for (const file of readdirSync(biomesDir)
  .filter(f => f.endsWith(".ts"))
  .sort()) {
  const src = readFileSync(join(biomesDir, file), "utf-8");
  const key = /biomeId:\s*BiomeId\.([A-Z_]+)/.exec(src)?.[1];
  const linksSrc = /const biomeLinks:\s*BiomeLinks\s*=\s*\[([\s\S]*?)\];/.exec(src)?.[1];
  if (!key || linksSrc === undefined || biomeIds[key] === undefined) {
    throw new Error(`Could not parse the biome file ${file}`);
  }
  // Plain links are always offered, weighted links ([BiomeId.X, n]) with a 1/n chance: both are reachable
  const links = [...linksSrc.matchAll(/BiomeId\.([A-Z_]+)/g)].map(m => biomeIds[m[1]]);
  biomes.push({ id: biomeIds[key], name: toTitle(key), links });
}
biomes.sort((a, b) => a.id - b.id);

const py = [];
py.push("# Generated by archipelago/generate-apworld-data.mjs - do not edit by hand.");
py.push("");
py.push(`GAME_NAME = ${JSON.stringify(apData.game)}`);
py.push(`DATA_VERSION = ${apData.version}`);
py.push(`BASE_ID = ${apData.base_id}`);
py.push(`FINAL_WAVE = ${apData.final_wave}`);
py.push(`GATE_INTERVAL = ${apData.gate_interval}`);
py.push(`WAVE_LOCATION_OFFSET = ${apData.wave_location_offset}`);
py.push(`SHOP_LOCATION_OFFSET = ${apData.shop_location_offset}`);
py.push(`BIOME_LOCATION_OFFSET = ${apData.biome_location_offset}`);
py.push(`POKEMON_ITEM_OFFSET = ${apData.pokemon_item_offset}`);
py.push(`BIOME_PASS_OFFSET = ${apData.biome_pass_offset}`);
py.push(`WAVE_BONUS_LOCATION_OFFSET = ${apData.wave_bonus_location_offset}`);
py.push("# Waves at which the regular shop gets new items (each one unlocks a batch of Archipelago shop items)");
py.push(`SHOP_TIER_WAVES = [${apData.shop_tier_waves.join(", ")}]`);
py.push("# Blitz option: last floor and shop tiers (the regular shop follows the virtual floor, twice the real one)");
py.push(`BLITZ_FINAL_WAVE = ${apData.blitz_final_wave}`);
py.push(`BLITZ_SHOP_TIER_WAVES = [${apData.blitz_shop_tier_waves.join(", ")}]`);
py.push("");
py.push("# Maximum number of stacks the player can hold, for the permanent bonus items");
py.push("ITEM_MAX = {");
for (const item of apData.items.filter(i => i.max !== undefined)) {
  py.push(`    ${JSON.stringify(item.name)}: ${item.max},`);
}
py.push("}");
py.push("");
py.push("# (biome id, name, ids of the biomes it links to)");
py.push("BIOMES = [");
for (const b of biomes) {
  py.push(`    (${b.id}, ${JSON.stringify(b.name)}, [${b.links.join(", ")}]),`);
}
py.push("]");
py.push("");
py.push("# (name, id, category, classification)");
py.push("ITEMS = [");
for (const item of apData.items) {
  py.push(
    `    (${JSON.stringify(item.name)}, ${apData.base_id + item.offset}, ${JSON.stringify(item.category)}, ${JSON.stringify(item.classification)}),`,
  );
}
py.push("]");
py.push("");
py.push("# Starter generation and types (base form), by item name");
py.push("POKEMON_INFO = {");
for (const p of pokemon) {
  py.push(`    ${JSON.stringify(p.name)}: (${p.generation}, ${JSON.stringify(p.types)}),`);
}
py.push("}");
py.push("");
py.push("# (name, id, starter cost)");
py.push("POKEMON = [");
for (const p of pokemon) {
  py.push(`    (${JSON.stringify(p.name)}, ${p.id}, ${p.cost}),`);
}
py.push("]");
py.push("");

const out = join(root, "archipelago/apworld/pokerogue/data.py");
writeFileSync(out, py.join("\n"), "utf-8");
console.log(`Wrote ${apData.items.length} items, ${pokemon.length} Pokemon and ${biomes.length} biomes to ${out}`);
