// Generates archipelago/apworld/pokerogue/data.py from the game sources so that the apworld
// and the game client always share the same item / location ids.
//
// Usage: node archipelago/generate-apworld-data.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const apData = JSON.parse(readFileSync(join(root, "src/archipelago/ap-data.json"), "utf-8"));

// --- SpeciesId enum (sequential values with explicit overrides) ---
const speciesSrc = readFileSync(join(root, "src/enums/species-id.ts"), "utf-8");
const enumBody = speciesSrc.slice(speciesSrc.indexOf("{") + 1, speciesSrc.lastIndexOf("}"));
const speciesIds = {};
let next = 0;
for (const rawLine of enumBody.split(/\r?\n/)) {
  const line = rawLine
    .replace(/\/\*.*?\*\//g, "")
    .replace(/\/\/.*$/, "")
    .trim();
  const match = /^([A-Z0-9_]+)\s*(?:=\s*(\d+))?\s*,?$/.exec(line);
  if (!match) {
    continue;
  }
  const value = match[2] === undefined ? next : Number.parseInt(match[2]);
  speciesIds[match[1]] = value;
  next = value + 1;
}

// --- Starters: species data entries that define a `starterCost` (src/data/balance/species/generation-XX.ts) ---
const speciesDir = join(root, "src/data/balance/species");
const starters = [];
for (const file of readdirSync(speciesDir)
  .filter(f => /^generation-\d+\.ts$/.test(f))
  .sort()) {
  const src = readFileSync(join(speciesDir, file), "utf-8");
  // Each species is declared as `generationXSpeciesData[SpeciesId.NAME] = { ... }`
  const blocks = src.split(/SpeciesData\[SpeciesId\./).slice(1);
  for (const block of blocks) {
    const key = /^([A-Z0-9_]+)\]/.exec(block)?.[1];
    const cost = /\bstarterCost:\s*(\d+)/.exec(block)?.[1];
    if (key && cost) {
      starters.push({ key, cost: Number.parseInt(cost) });
    }
  }
}

const toTitle = key =>
  key
    .split("_")
    .map(w => w.charAt(0) + w.slice(1).toLowerCase())
    .join(" ");

const pokemon = starters
  .filter(s => speciesIds[s.key] !== undefined)
  .map(s => ({
    name: `Pokemon - ${toTitle(s.key)}`,
    id: apData.base_id + apData.pokemon_item_offset + speciesIds[s.key],
    cost: s.cost,
  }));

const py = [];
py.push("# Generated by archipelago/generate-apworld-data.mjs - do not edit by hand.");
py.push("");
py.push(`GAME_NAME = ${JSON.stringify(apData.game)}`);
py.push(`DATA_VERSION = ${apData.version}`);
py.push(`BASE_ID = ${apData.base_id}`);
py.push(`FINAL_WAVE = ${apData.final_wave}`);
py.push(`GATE_INTERVAL = ${apData.gate_interval}`);
py.push(`WAVE_LOCATION_OFFSET = ${apData.wave_location_offset}`);
py.push(`SHOP_LOCATION_OFFSET = ${apData.shop_location_offset}`);
py.push(`POKEMON_ITEM_OFFSET = ${apData.pokemon_item_offset}`);
py.push("");
py.push("# (name, id, category, classification)");
py.push("ITEMS = [");
for (const item of apData.items) {
  py.push(
    `    (${JSON.stringify(item.name)}, ${apData.base_id + item.offset}, ${JSON.stringify(item.category)}, ${JSON.stringify(item.classification)}),`,
  );
}
py.push("]");
py.push("");
py.push("# (name, id, starter cost)");
py.push("POKEMON = [");
for (const p of pokemon) {
  py.push(`    (${JSON.stringify(p.name)}, ${p.id}, ${p.cost}),`);
}
py.push("]");
py.push("");

const out = join(root, "archipelago/apworld/pokerogue/data.py");
writeFileSync(out, py.join("\n"), "utf-8");
console.log(`Wrote ${apData.items.length} items and ${pokemon.length} Pokemon to ${out}`);
